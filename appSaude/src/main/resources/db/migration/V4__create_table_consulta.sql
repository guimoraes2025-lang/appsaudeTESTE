CREATE TABLE consulta (
    id_consulta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_consulta DATE NOT NULL,
    hora_consulta TIME NOT NULL,
    status_consulta VARCHAR(20) NOT NULL DEFAULT 'AGENDADA'
        CHECK (status_consulta IN ('AGENDADA', 'CONFIRMADA', 'REALIZADA', 'CANCELADA')),
    observacoes TEXT,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paciente_id BIGINT NOT NULL REFERENCES paciente(id_paciente) ON DELETE RESTRICT,
    medico_id BIGINT NOT NULL REFERENCES medico(id_medico) ON DELETE RESTRICT,
    atendente_id BIGINT REFERENCES atendente(id_atendente) ON DELETE RESTRICT
);

CREATE INDEX idx_consulta_paciente ON consulta(paciente_id);
CREATE INDEX idx_consulta_medico ON consulta(medico_id);
CREATE INDEX idx_consulta_atendente ON consulta(atendente_id);
CREATE UNIQUE INDEX uq_consulta_medico_horario_ativo
    ON consulta(medico_id, data_consulta, hora_consulta)
    WHERE status_consulta <> 'CANCELADA';
